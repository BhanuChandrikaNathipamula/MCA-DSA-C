/*Operators :
   1) Arithematic operator*/

#include <stdio.h>
void main()
{
    int a, b;
    printf("Enter a and b values:");
    scanf("%d%d", &a, &b);
    printf("sum :%d\n ", a + b);
    printf("subtract :%d\n ", a - b);
    printf("mul :%d\n ", a * b);
    printf("div :%d\n ", a / b);
    printf("modulo :%d\n ", a % b);
}