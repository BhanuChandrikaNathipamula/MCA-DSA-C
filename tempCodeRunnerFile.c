#include<stdio.h>
void main(){
    int a,b;
    printf("Enter a and b values:");     // 2 3
    scanf("%d%d",&a,&b);
    printf("sum :%d\n ",a+b);            // 5
    printf("subtract :%d\n ",a-b);      // 1
    printf("mul :%d\n ",a*b);           //6
    printf("div :%d\n ",a/b);           //1
    printf("modulo :%d\n ",a%b);        // //1
}